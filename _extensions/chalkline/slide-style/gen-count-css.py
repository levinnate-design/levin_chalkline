#!/usr/bin/env python3
"""TO BE REMOVED with slide-style.lua (see there).
Writes slide-style-count.css: how each type reflows for 1-9 cards.
The Lua filter sets data-ss-count on the slide; these rules read it. No JavaScript needed."""
MAXN = 9

def layout(t, n):
    if t == "row":
        cols = n if n <= 5 else -(-n // 2)
        return cols, -(-n // cols)
    if t == "grid":
        tiles = n + 1  # the THINK question is one tile
        cols = tiles if tiles <= 3 else max(2, -(-tiles // 2))
        return cols, -(-tiles // cols)
    return 1, n

def sel(pairs, extra=""):
    return [f'section.ss[data-ss-type={t}][data-ss-count="{n}"]{extra}' for t, n in pairs]

def rule(sels, suffix, body):
    return ",\n".join(s + suffix for s in sels) + " {" + body + "}\n"

out = ["/* GENERATED by gen-count-css.py. Do not edit by hand. */\n"]
for t in ("row", "grid"):
    for n in range(1, MAXN + 1):
        cols, rows = layout(t, n)
        out.append(f'section.ss[data-ss-type={t}][data-ss-count="{n}"]{{--cols:{cols};--crow:{rows}}}\n')
for n in range(1, MAXN + 1):
    out.append(f'section.ss[data-ss-type=table][data-ss-count="{n}"]{{--n:{n}}}\n')

compact = [("row", n) for n in range(1, MAXN + 1) if layout("row", n)[1] == 2] + \
          [("grid", n) for n in range(1, MAXN + 1) if layout("grid", n)[1] == 2]
roomy = [("row", n) for n in (1, 2)] + [("table", n) for n in (1, 2, 3)] + [("grid", n) for n in (1, 2)]
snug = [("table", n) for n in (6, 7)]
tight = [("table", n) for n in (8, 9)]
S = sel(compact)

out.append("\n/* two rows of cards: smaller type, inline secondary language on small lines */\n")
out.append(rule(S, " .ss-card", "gap:3px;padding:var(--card-pad,10px 14px)"))
out.append(rule(S, " .ss-card .ss-name", "font-size:21px"))
out.append(rule(S, " .ss-card .ss-who", "font-size:17px"))
out.append(rule(S, " .ss-card .ss-idea", "font-size:19px"))
out.append(rule(S, " .ss-card .ss-text", "font-size:15px"))
out.append(rule(S, " .ss-card .ss-bi.ss-who,\n" + ",\n".join(s + " .ss-card .ss-bi.ss-text" for s in S), "flex-direction:row;flex-wrap:wrap;gap:0 8px;align-items:baseline"))
out.append(rule(S, " .ss-schools", "gap:12px"))
out.append(rule(S + sel(tight), " h2", "font-size:30px"))
out.append(rule(S, "[data-ss-img=thumb] .ss-pic", "width:40px;height:40px;right:-14px;top:-16px;z-index:2"))
out.append(rule(S, "[data-ss-img=thumb] .ss-card .ss-name", "padding-right:0"))
strip = [p for p in compact if layout(*p)[0] <= 3] + [p for p in roomy if p[0] != 'table'] + [('row', 3)]
fall = [p for p in compact if layout(*p)[0] >= 4]
for img in ("banner", "duotone", "frame"):
    out.append(rule(sel(strip, f"[data-ss-img={img}]"), " .ss-card", "padding-right:36%"))
    out.append(rule(sel(strip, f"[data-ss-img={img}]"), " .ss-pic", "position:absolute;right:10px;top:10px;bottom:10px;width:31%;height:auto;order:0"))
out.append(rule(sel(strip, "[data-ss-img=frame]"), " .ss-pic", "display:flex!important;flex-direction:column"))
out.append(rule(sel(strip, "[data-ss-img=frame]"), " .ss-pic img", "height:calc(100% - 20px)"))
# narrow columns: banner, frame and duotone shrink to the corner thumb
for img in ("banner", "duotone", "frame"):
    F = sel(fall, f"[data-ss-img={img}]")
    out.append(rule(F, " .ss-pic", "position:absolute;right:-14px;top:-16px;z-index:2;width:40px;height:40px;border-radius:50%;overflow:hidden;border:3px solid var(--accent);padding:0;background:none;order:0"))
    out.append(rule(F, " .ss-pic .ss-figcap", "display:none"))
    out.append(rule(F, " .ss-pic img", "height:100%;filter:none;mix-blend-mode:normal;opacity:1"))

out.append("\n/* few cards: bigger type so the slide does not look empty */\n")
R = sel(roomy)
out.append(rule(R, " .ss-card .ss-name", "font-size:34px"))
out.append(rule(R, " .ss-card .ss-who", "font-size:24px"))
out.append(rule(R, " .ss-card .ss-idea", "font-size:30px"))
out.append(rule(R, " .ss-card .ss-text", "font-size:22px"))
out.append(rule(R, " .ss-card", "padding:var(--card-pad,22px 26px);gap:12px"))
T3 = sel([p for p in roomy if p[0] == "table"])
out.append(rule(T3, " .ss-card .ss-name", "font-size:30px"))
out.append(rule(T3, " .ss-card .ss-idea", "font-size:28px"))
out.append(rule(T3, " .ss-card .ss-who", "font-size:22px"))

out.append("\n/* long tables: smaller type, then one line per row */\n")
SN = sel(snug)
out.append(rule(SN, " .ss-card", "padding:2px 12px"))
out.append(rule(SN, " .ss-card .ss-name", "font-size:19px"))
out.append(rule(SN, " .ss-card .ss-who", "font-size:16px"))
out.append(rule(SN, " .ss-card .ss-idea", "font-size:18px"))
out.append(rule(SN, " .ss-card .ss-text", "font-size:14px"))
TI = sel(tight)
out.append(rule(TI, " .ss-schools", "gap:4px"))
out.append(rule(TI, " .ss-card", "padding:0 12px;border-radius:8px"))
out.append(rule(TI, " .ss-card .ss-bi", "flex-direction:row;flex-wrap:nowrap;gap:8px;align-items:baseline"))
out.append(rule(TI, " .ss-card .ss-name", "font-size:18px"))
out.append(rule(TI, " .ss-card .ss-who", "font-size:16px"))
out.append(rule(TI, " .ss-card .ss-idea", "font-size:17px"))
out.append(rule(TI, " .ss-card .ss-text", "font-size:14px"))
out.append(rule(TI, " .ss-think", "padding:8px 20px"))
out.append(rule(TI, "[data-ss-img]:not([data-ss-img=none]) .ss-pic", "width:26px;height:26px;border-width:2px"))
out.append(rule(SN, "[data-ss-img]:not([data-ss-img=none]) .ss-pic", "width:36px;height:36px;border-width:2px"))
open("slide-style-count.css", "w").write("".join(out))
print("ok", len("".join(out)))
