"""Import terms and images from the vocab list (vocab/) into a unit.

vocab/data/vocab.csv is the source of truth for the course's words. This script copies
the terms you list into a course/vocab/ file here, and copies their images into
the unit folder (course/units/<folder>/images/). Re-run it whenever the vocab list changes; it overwrites both.

Example (run from the repo root):

    python chalkline.py import-vocab \\
        --unit 1 --title "Ancient Greece" --folder 01-ancient-greece \\
        --ids GRC-001 GRC-002 GRC-003 \\
        --image-ids GRC-010

    --ids         terms to add to the unit's vocab file (and copy their images)
    --image-ids   extra images to copy without adding the term to the vocab list
"""

import argparse
import csv
import shutil
import subprocess
from pathlib import Path

import yaml

from extension import ROOT  # noqa: E402  (the course folder)


def source_commit(source):
    """The vocab folder's current git commit, so the vocab file records where it came from."""
    try:
        return subprocess.run(["git", "-C", str(source), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", default="vocab", help="path to the vocab folder (default: vocab)")
    parser.add_argument("--unit", required=True, type=int)
    parser.add_argument("--title", required=True, help="unit title")
    parser.add_argument("--folder", required=True, help="unit folder name, like 01-ancient-greece")
    parser.add_argument("--ids", nargs="+", required=True)
    parser.add_argument("--image-ids", nargs="*", default=[])
    args = parser.parse_args()

    source = Path(args.source)
    rows = {r["id"]: r for r in csv.DictReader(open(source / "data" / "vocab.csv", encoding="utf-8"))}
    missing = [i for i in args.ids + args.image_ids if i not in rows]
    if missing:
        raise SystemExit(f"Not found in {source}/data/vocab.csv: {', '.join(missing)}")

    image_dir = ROOT / "course" / "units" / args.folder / "images"
    image_dir.mkdir(parents=True, exist_ok=True)

    terms = []
    for i in args.ids:
        r = rows[i]
        entry = {"term": r["term_en"], "definition": r["short_def"]}
        if r["example"]:
            entry["example"] = r["example"]
        if r["explanation"]:
            entry["notes"] = r["explanation"]
        if r["zh"]:
            entry["zh"] = r["zh"]   # reference materials only, never flashcards/quizzes
        if r["image"]:
            entry["image"] = r["image"]
        entry["id"] = i
        terms.append(entry)

    copied = 0
    for i in args.ids + args.image_ids:
        img = rows[i]["image"]
        if img:
            shutil.copy2(source / "images" / img, image_dir / img)
            copied += 1

    header = (
        f"# Generated by `python chalkline.py import-vocab` from {source.as_posix()}/data/vocab.csv (commit {source_commit(source)}).\n"
        f"# Edit terms in {source.as_posix()}/data/vocab.csv, then re-run the script. Don't edit this file by hand.\n\n"
    )
    out = ROOT / "course" / "vocab" / f"{args.folder}.yml"
    body = yaml.safe_dump({"unit": args.unit, "unit_title": args.title, "terms": terms},
                          allow_unicode=True, sort_keys=False, width=1000)
    out.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(terms)} terms to {out.relative_to(ROOT)} and {copied} images to {image_dir.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
