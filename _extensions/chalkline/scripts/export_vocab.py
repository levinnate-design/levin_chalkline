"""Export every vocab file to Quizlet, Kahoot, and Anki formats in one run.

Run from the repo root:

    python chalkline.py export-vocab              # all units
    python chalkline.py export-vocab --units 1 3  # only units 1 and 3

Writes into exports/:
    quizlet/unit-01.txt      tab-separated, one per unit, plus all-units.txt
    kahoot/unit-01.xlsx      one Kahoot quiz per unit, in Kahoot's import layout
    anki/course-vocab.apkg   one Anki deck file, with a sub-deck per unit
"""

import argparse
import hashlib
import random
from pathlib import Path

from vocab import load_all

from extension import ROOT  # noqa: E402

EXPORTS = ROOT / "exports"

# --- Kahoot settings -------------------------------------------------------
# Kahoot's import template labels the limits as 120 (question) and 75 (answers),
# but Kahoot's help page says the import itself is stricter. These safer limits
# avoid rejected rows. Raise them if Kahoot ever accepts longer text.
KAHOOT_QUESTION_MAX = 95
KAHOOT_ANSWER_MAX = 60
KAHOOT_TIME_LIMIT = 20   # seconds. Allowed: 5, 10, 20, 30, 60, 90, 120, 240

# The layout of Kahoot's "Quiz template" spreadsheet: headers on row 8,
# columns B-H, questions start on row 9, column A holds the question number.
KAHOOT_HEADER_ROW = 8
KAHOOT_HEADERS = [
    "Question - max 120 characters",
    "Answer 1 - max 75 characters",
    "Answer 2 - max 75 characters",
    "Answer 3 - max 75 characters",
    "Answer 4 - max 75 characters",
    "Time limit (sec) – 5, 10, 20, 30, 60, 90, 120, or 240 secs",
    "Correct answer(s) - choose at least one",
]


def by_unit(terms):
    """Group terms into {unit_number: [terms]}."""
    units = {}
    for t in terms:
        units.setdefault(t["unit"], []).append(t)
    return units


def one_line(text):
    """Quizlet uses tabs and new lines as separators, so remove them from the text."""
    return " ".join(text.split())


# --- Quizlet ---------------------------------------------------------------

def write_quizlet(units, out_dir):
    """Tab between term and definition, one card per line.
    In Quizlet's import box choose: Between term and definition = Tab,
    Between rows = New line."""
    out_dir.mkdir(parents=True, exist_ok=True)
    everything = []
    for unit, terms in units.items():
        lines = [f"{one_line(t['term'])}\t{one_line(t['definition'])}" for t in terms]
        everything.extend(lines)
        (out_dir / f"unit-{unit:02d}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out_dir / "all-units.txt").write_text("\n".join(everything) + "\n", encoding="utf-8")
    print(f"  Quizlet: {len(units)} unit file(s) + all-units.txt")


# --- Kahoot ----------------------------------------------------------------

def kahoot_rows(terms, all_terms):
    """Turn each term into a question: show the definition, pick the right term.

    Wrong answers come from the same unit (or other units if the unit is small).
    The shuffle is seeded by the term, so re-running gives the same quiz.
    Returns (rows, problems).
    """
    rows, problems = [], []
    for t in terms:
        question = t["kahoot_question"] or t["definition"]
        if len(question) > KAHOOT_QUESTION_MAX:
            problems.append(
                f"'{t['term']}' (unit {t['unit']}): question is {len(question)} characters, "
                f"limit {KAHOOT_QUESTION_MAX}. Add a shorter 'kahoot_question' to the vocab file."
            )
            continue

        rng = random.Random(t["term"])
        same_unit = [x["term"] for x in terms if x["term"] != t["term"]]
        others = [x["term"] for x in all_terms if x["term"] != t["term"] and x["term"] not in same_unit]
        rng.shuffle(same_unit)
        rng.shuffle(others)
        choices = [t["term"]] + (same_unit + others)[:3]
        rng.shuffle(choices)

        too_long = [c for c in choices if len(c) > KAHOOT_ANSWER_MAX]
        if too_long:
            problems.append(f"'{t['term']}': answer longer than {KAHOOT_ANSWER_MAX} characters: {too_long}")
            continue

        correct = choices.index(t["term"]) + 1
        rows.append([question, *choices, *[""] * (4 - len(choices)), KAHOOT_TIME_LIMIT, correct])
    return rows, problems


def write_kahoot(units, all_terms, out_dir):
    from openpyxl import Workbook

    out_dir.mkdir(parents=True, exist_ok=True)
    all_problems = []
    for unit, terms in units.items():
        rows, problems = kahoot_rows(terms, all_terms)
        all_problems.extend(problems)

        wb = Workbook()
        ws = wb.active
        ws.title = "Sheet1"
        ws["B2"] = f"Unit {unit}: {terms[0]['unit_title']} vocab"
        ws["B4"] = "Generated by scripts/export_vocab.py. Import at kahoot.com: Create > Add question > Import spreadsheet."
        for col, header in enumerate(KAHOOT_HEADERS, start=2):
            ws.cell(row=KAHOOT_HEADER_ROW, column=col, value=header)
        for i, row in enumerate(rows, start=1):
            r = KAHOOT_HEADER_ROW + i
            ws.cell(row=r, column=1, value=i)
            for col, value in enumerate(row, start=2):
                ws.cell(row=r, column=col, value=value)
        ws.column_dimensions["B"].width = 60
        for c in "CDEF":
            ws.column_dimensions[c].width = 22
        wb.save(out_dir / f"unit-{unit:02d}.xlsx")

    print(f"  Kahoot:  {len(units)} quiz file(s)")
    for p in all_problems:
        print(f"    SKIPPED {p}")


# --- Anki ------------------------------------------------------------------

def stable_id(text):
    """Anki needs fixed numeric IDs so re-importing updates cards instead of duplicating them."""
    return int(hashlib.sha1(text.encode()).hexdigest()[:8], 16)


def write_anki(units, out_dir):
    try:
        import genanki
    except ImportError:
        print("  Anki:    skipped (run `pip install genanki` to enable)")
        return

    model = genanki.Model(
        stable_id("course-vocab-model"),
        "Course Vocab",
        fields=[{"name": "Term"}, {"name": "Definition"}, {"name": "Example"}],
        templates=[{
            "name": "Term -> Definition",
            "qfmt": "<h2>{{Term}}</h2>",
            "afmt": "{{FrontSide}}<hr id=answer>{{Definition}}"
                    "{{#Example}}<br><br><i>{{Example}}</i>{{/Example}}",
        }],
    )

    decks = []
    for unit, terms in units.items():
        name = f"Course Vocab::Unit {unit:02d} {terms[0]['unit_title']}"
        deck = genanki.Deck(stable_id(name), name)
        for t in terms:
            deck.add_note(genanki.Note(
                model=model,
                fields=[t["term"], t["definition"], t["example"]],
                guid=genanki.guid_for(t["unit"], t["term"]),
            ))
        decks.append(deck)

    out_dir.mkdir(parents=True, exist_ok=True)
    genanki.Package(decks).write_to_file(out_dir / "course-vocab.apkg")
    print(f"  Anki:    course-vocab.apkg ({len(decks)} sub-deck(s))")


# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--units", type=int, nargs="*", help="only export these unit numbers")
    args = parser.parse_args()

    all_terms = load_all()
    terms = [t for t in all_terms if not args.units or t["unit"] in args.units]
    if not terms:
        raise SystemExit("No vocab terms found. Check the course/vocab/ folder and --units.")
    units = by_unit(terms)

    print(f"Exporting {len(terms)} terms from {len(units)} unit(s) to {EXPORTS}/")
    write_quizlet(units, EXPORTS / "quizlet")
    write_kahoot(units, all_terms, EXPORTS / "kahoot")
    write_anki(units, EXPORTS / "anki")
    print("Done.")


if __name__ == "__main__":
    main()
